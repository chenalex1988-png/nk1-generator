def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--skel", required=True)
    ap.add_argument("--draft", required=True, help="受驗草稿檔名與 sha8（寫入表頭）")
    ap.add_argument("--xlsx", required=True)
    a = ap.parse_args()
    sk = fy.load(a.skel)
    head = ["節碼", "節名", "段", "生成"] + [f"{n} 命中／未命中" for n, *_ in ITEMS] + ["備註", "整體結論"]
